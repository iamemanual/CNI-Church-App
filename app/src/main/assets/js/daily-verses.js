    getDailyVerse: function(targetDate) {
      const d = targetDate ? new Date(targetDate) : new Date();
      if (isNaN(d.getTime())) return DAILY_VERSES[0];

      const month = String(d.getMonth() + 1).padStart(2, '0');
      const day = String(d.getDate()).padStart(2, '0');
      const mmdd = month + '-' + day;

      const matched = DAILY_VERSES.find(function(v) { return v.mmdd === mmdd; });
      if (matched) return matched;

      const start = new Date(d.getFullYear(), 0, 0);
      const diff = (d - start) + ((start.getTimezoneOffset() - d.getTimezoneOffset()) * 60 * 1000);
      const oneDay = 1000 * 60 * 60 * 24;
      const dayOfYear = Math.floor(diff / oneDay);
      const idx = ((dayOfYear - 1) % DAILY_VERSES.length + DAILY_VERSES.length) % DAILY_VERSES.length;
      return DAILY_VERSES[idx] || DAILY_VERSES[0];
    }
